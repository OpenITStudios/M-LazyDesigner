//! Private, opt-in Rust document recovery snapshots. These are NOT user
//! .bbmodel saves: no source file is ever opened for writing or overwritten.
//! SOURCE ONLY; local filesystem/Windows execution remains NOT_EXECUTED.

use lazydesigner::authoring::{sha256, storage, EditorSession, MAX_MODEL_BYTES};
use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::UNIX_EPOCH;

const PREFIX: &str = "ldrec-";
const SUFFIX: &str = ".bbmodel";
const MAX_CATALOG: usize = 512;
const KEEP_PER_SESSION: usize = 3;

type Result<T> = std::result::Result<T, String>;
fn fail(code: &'static str) -> String { code.into() }

#[derive(Clone, Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryEntry {
    pub id: String,
    pub epoch: u64,
    pub revision: u64,
    pub size_bytes: u64,
    pub modified_unix_ms: u64,
    // Listing a filename is never a content-integrity or visual verdict.
    pub integrity: &'static str,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RecoveryCheckpointReceipt {
    #[serde(flatten)]
    pub entry: RecoveryEntry,
    // Old, verified private checkpoints are pruned only after a new one
    // is readable. A failed prune does not invalidate the saved checkpoint.
    pub retention_complete: bool,
}

fn hex_lower(value: &str, length: usize) -> bool {
    value.len() == length && value.bytes().all(|byte|
        byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

// Names are generated by the native host. Untrusted UI-provided ids must be
// exact canonical basenames so they can never select an arbitrary file.
fn parse_id(id: &str) -> Option<(&str, u64, u64, &str)> {
    let stem = id.strip_prefix(PREFIX)?.strip_suffix(SUFFIX)?;
    let mut parts = stem.split('-');
    let (run, epoch_text, rev_text, digest) =
        (parts.next()?, parts.next()?, parts.next()?, parts.next()?);
    if parts.next().is_some() || !hex_lower(run, 32) ||
        !hex_lower(digest, 64) { return None; }
    let epoch = epoch_text.parse::<u64>().ok()?;
    let revision = rev_text.parse::<u64>().ok()?;
    if epoch.to_string() != epoch_text || revision.to_string() != rev_text {
        return None;
    }
    Some((run, epoch, revision, digest))
}

fn safe_dir(dir: &Path, create: bool) -> Result<bool> {
    // Caller derives dir from Tauri app_local_data_dir only, never from an
    // agent, a project filename, or a model-supplied path.
    let root = dir.parent().ok_or_else(|| fail("RECOVERY_ROOT_UNAVAILABLE"))?;
    if create {
        fs::create_dir_all(root).map_err(|_| fail("RECOVERY_ROOT_UNAVAILABLE"))?;
    }
    let root_stat = match fs::symlink_metadata(root) {
        Ok(stat) => stat,
        Err(error) if !create && error.kind() == std::io::ErrorKind::NotFound =>
            return Ok(false),
        Err(_) => return Err(fail("RECOVERY_ROOT_UNAVAILABLE")),
    };
    if !root_stat.file_type().is_dir() {
        return Err(fail("RECOVERY_ROOT_UNSAFE"));
    }
    if create {
        match fs::create_dir(dir) {
            Ok(()) => {}
            Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {}
            Err(_) => return Err(fail("RECOVERY_DIRECTORY_UNAVAILABLE")),
        }
    }
    let stat = match fs::symlink_metadata(dir) {
        Ok(stat) => stat,
        Err(error) if !create && error.kind() == std::io::ErrorKind::NotFound =>
            return Ok(false),
        Err(_) => return Err(fail("RECOVERY_DIRECTORY_UNAVAILABLE")),
    };
    if !stat.file_type().is_dir() {
        return Err(fail("RECOVERY_DIRECTORY_UNSAFE"));
    }
    Ok(true)
}

fn entry_at(dir: &Path, name: &str) -> Result<RecoveryEntry> {
    let (_, epoch, revision, _) = parse_id(name)
        .ok_or_else(|| fail("RECOVERY_ID_INVALID"))?;
    let path = dir.join(name);
    let meta = fs::symlink_metadata(&path)
        .map_err(|_| fail("RECOVERY_FILE_UNAVAILABLE"))?;
    if !meta.file_type().is_file() || meta.len() == 0 ||
        meta.len() > MAX_MODEL_BYTES as u64 {
        return Err(fail("RECOVERY_FILE_INVALID"));
    }
    let modified_unix_ms = meta.modified().ok()
        .and_then(|time| time.duration_since(UNIX_EPOCH).ok())
        .map(|duration| duration.as_millis().min(u64::MAX as u128) as u64)
        .unwrap_or(0);
    Ok(RecoveryEntry {
        id: name.into(), epoch, revision, size_bytes: meta.len(),
        modified_unix_ms, integrity: "UNVERIFIED_UNTIL_OPEN",
    })
}

pub fn list(dir: &Path) -> Result<Vec<RecoveryEntry>> {
    if !safe_dir(dir, false)? { return Ok(Vec::new()); }
    let mut entries = Vec::new();
    let mut scanned = 0;
    for result in fs::read_dir(dir).map_err(|_| fail("RECOVERY_LIST_FAILED"))? {
        scanned += 1;
        if scanned > MAX_CATALOG { return Err(fail("RECOVERY_CATALOG_LIMIT")); }
        let item = result.map_err(|_| fail("RECOVERY_LIST_FAILED"))?;
        let name = item.file_name();
        let Some(name) = name.to_str() else { continue };
        if parse_id(name).is_none() { continue; }
        // Damaged or swapped candidates are never silently described as valid.
        if let Ok(entry) = entry_at(dir, name) { entries.push(entry); }
    }
    entries.sort_by(|a, b| b.modified_unix_ms.cmp(&a.modified_unix_ms)
        .then_with(|| b.id.cmp(&a.id)));
    Ok(entries)
}

pub fn open(dir: &Path, id: &str) -> Result<EditorSession> {
    let (_, _, _, expected_sha) = parse_id(id)
        .ok_or_else(|| fail("RECOVERY_ID_INVALID"))?;
    if !safe_dir(dir, false)? { return Err(fail("RECOVERY_DIRECTORY_UNAVAILABLE")); }
    let path = dir.join(id);
    let data = storage::read_bounded(&path, MAX_MODEL_BYTES)?;
    if sha256(&data) != expected_sha {
        return Err(fail("RECOVERY_SHA256_MISMATCH"));
    }
    EditorSession::open(&data).map_err(|_| fail("RECOVERY_MODEL_UNSUPPORTED"))
}

fn prune_verified(dir: &Path, run_id: &str, epoch: u64) -> Result<()> {
    let mut candidates: Vec<RecoveryEntry> = list(dir)?.into_iter().filter(|entry| {
        parse_id(&entry.id).is_some_and(|(run, number, _, _)|
            run == run_id && number == epoch)
    }).collect();
    candidates.sort_by(|a, b| b.revision.cmp(&a.revision));
    // Invalid checkpoint bytes remain untouched, so they cannot displace
    // a valid older recovery during automatic retention.
    let mut verified = 0;
    for entry in candidates {
        if open(dir, &entry.id).is_err() { continue; }
        verified += 1;
        if verified > KEEP_PER_SESSION {
            fs::remove_file(dir.join(&entry.id))
                .map_err(|_| fail("RECOVERY_RETENTION_INCOMPLETE"))?;
        }
    }
    Ok(())
}

pub fn checkpoint(
    dir: &Path, run_id: &str, epoch: u64, session: &EditorSession,
) -> Result<RecoveryCheckpointReceipt> {
    if !hex_lower(run_id, 32) || epoch == 0 {
        return Err(fail("RECOVERY_SESSION_INVALID"));
    }
    safe_dir(dir, true)?;
    let data = session.export()?;
    let digest = sha256(&data);
    let revision = session.summary().revision;
    let id = format!("{PREFIX}{run_id}-{epoch}-{revision}-{digest}{SUFFIX}");
    let path: PathBuf = dir.join(&id);
    match fs::symlink_metadata(&path) {
        Ok(meta) if meta.file_type().is_file() => {
            // Idempotence never trusts an existing filename without its bytes.
            let existing = storage::read_bounded(&path, MAX_MODEL_BYTES)?;
            if sha256(&existing) != digest {
                return Err(fail("RECOVERY_EXISTING_FILE_MISMATCH"));
            }
        }
        Ok(_) => return Err(fail("RECOVERY_EXISTING_FILE_INVALID")),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            storage::publish_new(&path, &data, MAX_MODEL_BYTES)?;
        }
        Err(_) => return Err(fail("RECOVERY_FILE_UNAVAILABLE")),
    }
    // Only a successfully reopened immutable saved version is retained.
    open(dir, &id)?;
    let entry = entry_at(dir, &id)?;
    let retention_complete = prune_verified(dir, run_id, epoch).is_ok();
    Ok(RecoveryCheckpointReceipt { entry, retention_complete })
}

#[cfg(test)]
mod tests {
    use super::*;
    use lazydesigner::authoring::EditOperation;
    use rand::RngCore;

    fn fixture() -> PathBuf {
        let mut nonce = [0u8; 8];
        rand::rng().fill_bytes(&mut nonce);
        let root = std::env::temp_dir().join(format!(
            "ld-rust-recovery-{:016x}", u64::from_le_bytes(nonce)));
        fs::create_dir_all(&root).unwrap();
        root.join("rust-recovery")
    }

    const RUN: &str = "0123456789abcdef0123456789abcdef";

    #[test]
    fn private_checkpoint_restores_editable_bbmodel_and_rejects_invalid_ids() {
        let dir = fixture();
        let original = include_bytes!("../fixtures/bedrock-basic.bbmodel");
        let session = EditorSession::open(original).unwrap();
        let receipt = checkpoint(&dir, RUN, 7, &session).unwrap();
        assert_eq!(receipt.entry.epoch, 7);
        assert_eq!(receipt.entry.revision, 0);
        assert_eq!(list(&dir).unwrap().len(), 1);
        assert_eq!(open(&dir, &receipt.entry.id).unwrap().export().unwrap(),
            session.export().unwrap());
        assert!(open(&dir, "../source.bbmodel").is_err());
        assert!(open(&dir, "ldrec-invalid.bbmodel").is_err());
        assert_eq!(checkpoint(&dir, RUN, 7, &session).unwrap().entry.id,
            receipt.entry.id);
        fs::remove_dir_all(dir.parent().unwrap()).unwrap();
    }

    #[test]
    fn malformed_or_tampered_snapshot_is_never_restored_or_overwritten() {
        let dir = fixture();
        let source = EditorSession::open(
            include_bytes!("../fixtures/bedrock-basic.bbmodel")).unwrap();
        let receipt = checkpoint(&dir, RUN, 1, &source).unwrap();
        let path = dir.join(&receipt.entry.id);
        fs::write(&path, b"corrupt").unwrap();
        assert_eq!(open(&dir, &receipt.entry.id).err().unwrap(),
            "RECOVERY_SHA256_MISMATCH");
        assert!(checkpoint(&dir, RUN, 1, &source).is_err());
        assert_eq!(fs::read(&path).unwrap(), b"corrupt");
        fs::remove_dir_all(dir.parent().unwrap()).unwrap();
    }

    #[test]
    fn retains_three_newest_valid_snapshots_without_touching_original_source() {
        let dir = fixture();
        let source = include_bytes!("../fixtures/bedrock-basic.bbmodel");
        let mut session = EditorSession::open(source).unwrap();
        let uuid = session.document().cubes[0].uuid.clone();
        let mut ids = Vec::new();
        for revision in 0..4 {
            let receipt = checkpoint(&dir, RUN, 10, &session).unwrap();
            ids.push(receipt.entry.id);
            if revision < 3 {
                session.apply(revision, &[EditOperation::TranslateCube {
                    uuid: uuid.clone(), delta: [1.0, 0.0, 0.0],
                }]).unwrap();
            }
        }
        assert_eq!(list(&dir).unwrap().len(), 3);
        assert!(!dir.join(&ids[0]).exists());
        for id in &ids[1..] { assert!(open(&dir, id).is_ok()); }
        assert_eq!(source, include_bytes!("../fixtures/bedrock-basic.bbmodel"));
        fs::remove_dir_all(dir.parent().unwrap()).unwrap();
    }

    #[cfg(unix)]
    #[test]
    fn symlinked_recovery_directory_is_rejected() {
        use std::os::unix::fs::symlink;
        let dir = fixture();
        let outside = dir.parent().unwrap().join("outside");
        fs::create_dir(&outside).unwrap();
        symlink(&outside, &dir).unwrap();
        assert!(list(&dir).is_err());
        let source = EditorSession::open(
            include_bytes!("../fixtures/bedrock-basic.bbmodel")).unwrap();
        assert!(checkpoint(&dir, RUN, 3, &source).is_err());
        fs::remove_dir_all(dir.parent().unwrap()).unwrap();
    }
}
